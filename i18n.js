  function format(lang, key, params) {
    const table = MESSAGES[lang] || MESSAGES.zh;
    const text = table[key] != null ? table[key] : (MESSAGES.zh[key] != null ? MESSAGES.zh[key] : key);
    return text.replace(/\{(\w+)\}/g, (all, name) => {
      if (!params || !(name in params)) return all;
      const value = params[name];
      if (value && typeof value === 'object' && value.key) return format(lang, value.key, value.params);
      return String(value);
    });
  }

  // A stored message is a plain string or { key, params }.
  function render(lang, message) {
    if (message && typeof message === 'object' && message.key) return format(lang, message.key, message.params);
    return message == null ? '' : String(message);
  }

  const api = { MESSAGES, format, render };
  if (typeof module === 'object' && module.exports) module.exports = api;
  else root.I18N = api;
